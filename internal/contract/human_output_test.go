// The shared human-output helper is owned by package contract: one helper,
// consumed by the static renderer, the executor preset, and the orient/hook
// ContextPack summary. No second authority, config family, or capability
// offer for baseline behavior.

// Every load-bearing human-communication behavior the baseline must carry.
// These are semantics, not marker phrases: dropping any one weakens how a
// harness speaks to the human on every supported surface.
var humanOutputSemantics = []string{
	"Help the person understand and decide.",
	"Lead with the useful conclusion, change, or decision",
	"clear, concrete, active language",
	"natural rhythm, warmth, personality, and creative choices",
	"do not impose a rigid response template",
	"Separate observed facts from uncertainty, interpretation, and proposed action",
	"Choose the smallest useful medium",
	"prose for simple answers",
	"diagrams for relationships",
	"interactive HTML for exploration",
	"bespoke explainers or video",
	"Explain what evidence means first",
	"exact citations, identifiers, and technical detail available in drilldown",
	"Do not invent evidence",
	"hide gaps",
	"weaken governance",
	"spend/publish beyond the task's authority",
}

func TestHumanOutputBaselineCarriesHumanCommunicationSemantics(t *testing.T) {
	got := HumanOutputBaseline()
	if strings.TrimSpace(got) == "" {
		t.Fatal("HumanOutputBaseline() returned empty prose")
	}
	for _, want := range humanOutputSemantics {
		if !strings.Contains(got, want) {
			t.Fatalf("baseline lost human-communication behavior %q:\n%s", want, got)
		}
	}
	// The baseline is how a harness speaks — never a restatement of
	// Compound doctrine or a per-task outcome claim.
	for _, mustNot := range []string{"Compound", "substrate", "rented executor", "precedence", "<task>", "work_"} {
		if strings.Contains(got, mustNot) {
			t.Fatalf("baseline drifts off human communication (contains %q):\n%s", mustNot, got)
		}
	}
}

func TestHumanOutputOrientReminderIsSeparateStableEntryRule(t *testing.T) {
	reminder := HumanOutputOrientReminder()
	if reminder != HumanOutputOrientReminder() {
		t.Fatal("orient reminder is not deterministic across calls")
	}
	if !strings.Contains(reminder, "Begin non-trivial tasks with") ||
		!strings.Contains(reminder, "compound orient --harness <supported-name> --cwd <repository> --task <task>") ||
		!strings.Contains(reminder, "owned references from the served context") {
		t.Fatalf("orient reminder lost its entry-rule shape:\n%s", reminder)
	}
	if reminder == HumanOutputBaseline() || strings.Contains(reminder, "Help the person understand") {
		t.Fatalf("orient reminder collapsed into the baseline:\n%s", reminder)
	}
}

// staticHarnessInventory is the supported static-surface inventory, aliases
// included — the test must cover the inventory, not two canonical names.
var staticHarnessInventory = []string{"codex", "claude", "claude_code", "claude-code"}

func TestHumanOutputBaselineReachesEverySupportedStaticSurface(t *testing.T) {
	for _, harness := range staticHarnessInventory {
		t.Run(harness, func(t *testing.T) {
			root := t.TempDir()
			render, err := RenderInstructionBlock(instructionContractForTest(harness, "synthetic product task"), root)
			if err != nil {
				t.Fatal(err)
			}
			body := render.Content
			for _, want := range humanOutputSemantics {
				if !strings.Contains(body, want) {
					t.Fatalf("%s static block lost human-communication behavior %q", harness, want)
				}
			}
			// The reminder follows the baseline as its own paragraph, before
			// the doctrine bullets, on the real tracked surface shape.
			leadAt := strings.Index(body, "Help the person understand and decide.")
			orientAt := strings.Index(body, "Begin non-trivial tasks with")
			generatedAt := strings.Index(body, "Generated by `compound contract compile`")
			if leadAt < 0 || orientAt < 0 || generatedAt < 0 || !(leadAt < orientAt && orientAt < generatedAt) {
				t.Fatalf("%s static block does not order baseline → orient reminder → generated header:\n%s", harness, body)
			}
			// A static client has no session-start hook to serve the door
			// map, so the block must point at it before the doctrine.
			doorAt := strings.Index(body, HumanOutputDoorPointer())
			if doorAt < orientAt || doorAt > generatedAt || !strings.Contains(HumanOutputDoorPointer(), "run `compound doors serve`") {
				t.Fatalf("%s static block lost the door map pointer:\n%s", harness, body)
			}
		})
	}
	// An unsupported name has no static surface; the inventory above is the
	// whole set.
	if _, err := RenderInstructionBlock(instructionContractForTest("acme-harness", "x"), t.TempDir()); err == nil {
		t.Fatal("unsupported harness gained a static instruction surface")
	}
}

func TestHumanOutputBaselineReachesExecutorPreset(t *testing.T) {
	for _, harness := range staticHarnessInventory {
		t.Run(harness, func(t *testing.T) {
			root := t.TempDir()
			render, err := RenderInstructionBlockVariant(instructionContractForTest(harness, "executor charter fixture"), root, "executor")
			if err != nil {
				t.Fatal(err)
			}
			for _, want := range humanOutputSemantics {
				if !strings.Contains(render.Content, want) {
					t.Fatalf("%s executor preset lost human-communication behavior %q", harness, want)
				}
			}
			if !strings.Contains(render.Content, "Begin non-trivial tasks with") {
				t.Fatalf("%s executor preset lost the orient reminder:\n%s", harness, render.Content)
			}
			if !strings.Contains(render.Content, HumanOutputDoorPointer()) {
				t.Fatalf("%s executor preset lost the door map pointer:\n%s", harness, render.Content)
			}
		})
	}
}

