// Essence is the product's invariant: who it is for, the problem it solves, the
// value it gives, the goal it is run toward, what it must never do, and the
// stage it is in. It changes rarely; a Form changes whenever a signal arrives.
type Essence struct {
	Audience    string   `json:"audience,omitempty" yaml:"audience,omitempty"`
	Problem     string   `json:"problem,omitempty" yaml:"problem,omitempty"`
	Value       string   `json:"value,omitempty" yaml:"value,omitempty"`
	Goal        Goal     `json:"goal,omitzero" yaml:"goal,omitempty"`
	Constraints []string `json:"constraints,omitempty" yaml:"constraints,omitempty"`
	AntiGoals   []string `json:"anti_goals,omitempty" yaml:"anti_goals,omitempty"`
	Stage       string   `json:"stage,omitempty" yaml:"stage,omitempty"`
}

// Goal is what the product is run toward. A zero income target is unknown.
type Goal struct {
	IncomeTargetUSDMonth float64 `json:"income_target_usd_month,omitempty" yaml:"income_target_usd_month,omitempty"`
	Horizon              string  `json:"horizon,omitempty" yaml:"horizon,omitempty"`
}

// Form is the essence contracted for one (surface, stage): what must be true of
// the product on that surface at that stage, and how to tell that it is.
type Form struct {
	Surface    string            `json:"surface" yaml:"surface"`
	Stage      string            `json:"stage" yaml:"stage"`
	Goal       string            `json:"goal,omitempty" yaml:"goal,omitempty"`
	Parameters map[string]string `json:"parameters,omitempty" yaml:"parameters,omitempty"`
	Acceptance []string          `json:"acceptance,omitempty" yaml:"acceptance,omitempty"`
	Status     string            `json:"status,omitempty" yaml:"status,omitempty"`
}

// LearnedFact is something a stage measured about the product, with the date
// and the evidence that carries it.
type LearnedFact struct {
	At          time.Time `json:"at" yaml:"at"`
	Stage       string    `json:"stage,omitempty" yaml:"stage,omitempty"`
	Fact        string    `json:"fact" yaml:"fact"`
	EvidenceRef string    `json:"evidence_ref" yaml:"evidence_ref"`
}

const (
	// EssenceUnknown is the recorded answer for a declared essence field nobody
	// could source. It is an answer ("asked; unknown"), unlike an absent fact.
	EssenceUnknown = "unknown"
	// EssenceRecorded / EssenceNone are EssenceRecord statuses for a resolved
	// product; an unresolved or ambiguous query carries the Where status.
	EssenceRecorded = "recorded"
	EssenceNone     = "none"

	marketingRenderMarker = "<!-- generated by compound product render-marketing"
)

// EssenceRecord is the essence as the ledger currently holds it: rebuilt from
// the folded essence.*, form.*, learned.*, and taste.* facts of one product.
type EssenceRecord struct {
	Query     string        `json:"query,omitempty"`
	Status    string        `json:"status"`
	ProductID string        `json:"product_id,omitempty"`
	Essence   Essence       `json:"essence,omitzero"`
	Forms     []Form        `json:"forms,omitempty"`
	Learned   []LearnedFact `json:"learned,omitempty"`
	Taste     TasteProfile  `json:"taste,omitzero"`
	Next      string        `json:"next,omitempty"`
}

// formKey is the alphabet of a form's surface and stage. Both are segments of
// the form.<surface>.<stage>.<field> predicate, so a dot would make the fact
// unaddressable.
var formKey = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]*$`)

func validateEssence(p Product) error {
	if p.Essence.Goal.IncomeTargetUSDMonth < 0 {
		return fmt.Errorf("essence goal income_target_usd_month must not be negative")
	}
	seen := map[string]bool{}
	for i, f := range p.Forms {
		if !formKey.MatchString(f.Surface) || !formKey.MatchString(f.Stage) {
			return fmt.Errorf("forms[%d] surface %q and stage %q must match %s", i, f.Surface, f.Stage, formKey)
		}
		key := f.Surface + "." + f.Stage
		if seen[key] {
			return fmt.Errorf("forms[%d] duplicates form %s", i, key)
		}
		seen[key] = true
	}
	for i, l := range p.Learned {
		if l.At.IsZero() || strings.TrimSpace(l.Fact) == "" || strings.TrimSpace(l.EvidenceRef) == "" {
			return fmt.Errorf("learned[%d] needs at, fact, and evidence_ref", i)
		}
	}
	return nil
}

type productFact struct{ predicate, value string }

// essenceFacts are the essence.*, form.*, learned.*, and taste.* facts the
// product registry records for p. A declared essence records every field,
// writing EssenceUnknown for a blank one; an undeclared essence records none.
func essenceFacts(p Product) []productFact {
	var facts []productFact
	add := func(predicate, value string) {
		if strings.TrimSpace(value) == "" {
			value = EssenceUnknown
		}
		facts = append(facts, productFact{predicate, strings.TrimSpace(value)})
	}
	if e := p.Essence; essenceDeclared(e) {
		add("essence.audience", e.Audience)
		add("essence.problem", e.Problem)
		add("essence.value", e.Value)
		target := ""
		if e.Goal.IncomeTargetUSDMonth > 0 {
			target = strconv.FormatFloat(e.Goal.IncomeTargetUSDMonth, 'f', -1, 64)
		}
		add("essence.goal.income_target_usd_month", target)
		add("essence.goal.horizon", e.Goal.Horizon)
		add("essence.constraints", jsonList(e.Constraints))
		add("essence.anti_goals", jsonList(e.AntiGoals))
		add("essence.stage", e.Stage)
	}
	for _, f := range p.Forms {
		prefix := "form." + f.Surface + "." + f.Stage + "."
		add(prefix+"goal", f.Goal)
		params := ""
		if len(f.Parameters) > 0 {
			blob, _ := json.Marshal(f.Parameters) // map keys marshal sorted
			params = string(blob)
		}
		add(prefix+"parameters", params)
		add(prefix+"acceptance", jsonList(f.Acceptance))
		add(prefix+"status", f.Status)
	}
	learned := append([]LearnedFact(nil), p.Learned...)
	sort.SliceStable(learned, func(i, j int) bool { return learned[i].At.Before(learned[j].At) })
	for i, l := range learned {
		l.At = l.At.UTC()
		l.Stage, l.Fact, l.EvidenceRef = strings.TrimSpace(l.Stage), strings.TrimSpace(l.Fact), strings.TrimSpace(l.EvidenceRef)
		blob, _ := json.Marshal(l)
		add("learned."+strconv.Itoa(i+1), string(blob))
	}
	if list := jsonList(p.TasteProfile.Standards); list != "" {
		add("taste.standards", list)
	}
	if list := jsonList(p.TasteProfile.RedLines); list != "" {
		add("taste.red_lines", list)
	}
	return facts
}

func essenceDeclared(e Essence) bool {
	return strings.TrimSpace(e.Audience+e.Problem+e.Value+e.Goal.Horizon+e.Stage) != "" ||
		e.Goal.IncomeTargetUSDMonth != 0 || len(compact(e.Constraints)) > 0 || len(compact(e.AntiGoals)) > 0
}

// jsonList encodes a list fact. Items are sentences that may hold commas, so
// the comma-joined form other product facts use would not round-trip.
func jsonList(values []string) string {
	values = compact(values)
	if len(values) == 0 {
		return ""
	}
	blob, _ := json.Marshal(values)
	return string(blob)
}

func parseList(value string) []string {
	if value == "" || value == EssenceUnknown {
		return nil
	}
	var out []string
	if err := json.Unmarshal([]byte(value), &out); err != nil {
		return []string{value}
	}
	return out
}

// EssenceFromView rebuilds one product's essence record from the folded
// current view. ok reports whether an essence (not just forms or learned facts)
// is recorded for it.
func EssenceFromView(view *mem.CurrentView, entity string) (EssenceRecord, bool) {
	facts := map[string]mem.Claim{}
	if view != nil {
		for _, c := range view.Claims() {
			if c.Entity == entity {
				if prior, seen := facts[c.Predicate]; !seen || c.Seq > prior.Seq {
					facts[c.Predicate] = c
				}
			}
		}
	}
	return essenceRecordFromFacts(entity, facts), hasEssenceFacts(facts)
}

func hasEssenceFacts(facts map[string]mem.Claim) bool {
	for predicate := range facts {
		if strings.HasPrefix(predicate, "essence.") {
			return true
		}
	}
	return false
}

func essenceRecordFromFacts(entity string, facts map[string]mem.Claim) EssenceRecord {
	record := EssenceRecord{Status: EssenceNone, ProductID: entity}
	forms := map[string]*Form{}
	learned := map[int]LearnedFact{}
	for predicate, claim := range facts {
		value := claim.Object
		switch {
		case strings.HasPrefix(predicate, "essence."):
			setEssenceField(&record.Essence, strings.TrimPrefix(predicate, "essence."), value)
		case strings.HasPrefix(predicate, "form."):
			parts := strings.Split(strings.TrimPrefix(predicate, "form."), ".")
			if len(parts) != 3 {
				continue
			}
			key := parts[0] + "." + parts[1]
			if forms[key] == nil {
				forms[key] = &Form{Surface: parts[0], Stage: parts[1]}
			}
			setFormField(forms[key], parts[2], value)
		case strings.HasPrefix(predicate, "learned."):
			n, err := strconv.Atoi(strings.TrimPrefix(predicate, "learned."))
			var fact LearnedFact
			if err != nil || json.Unmarshal([]byte(value), &fact) != nil {
				continue
			}
			learned[n] = fact
		case predicate == "taste.standards":
			record.Taste.Standards = parseList(value)
		case predicate == "taste.red_lines":
			record.Taste.RedLines = parseList(value)
		default:
			continue
		}
		record.Status = EssenceRecorded
	}
	keys := make([]string, 0, len(forms))
	for key := range forms {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		record.Forms = append(record.Forms, *forms[key])
	}
	ns := make([]int, 0, len(learned))
	for n := range learned {
		ns = append(ns, n)
	}
	sort.Ints(ns)
	for _, n := range ns {
		record.Learned = append(record.Learned, learned[n])
	}
	return record
}

func setEssenceField(e *Essence, field, value string) {
	switch field {
	case "audience":
		e.Audience = value
	case "problem":
		e.Problem = value
	case "value":
		e.Value = value
	case "goal.income_target_usd_month":
		if v, err := strconv.ParseFloat(value, 64); err == nil {
			e.Goal.IncomeTargetUSDMonth = v
		}
	case "goal.horizon":
		e.Goal.Horizon = value
	case "constraints":
		e.Constraints = parseList(value)
	case "anti_goals":
		e.AntiGoals = parseList(value)
	case "stage":
		e.Stage = value
	}
}

func setFormField(f *Form, field, value string) {
	switch field {
	case "goal":
		f.Goal = value
	case "status":
		f.Status = value
	case "acceptance":
		f.Acceptance = parseList(value)
	case "parameters":
		if value != EssenceUnknown {
			var params map[string]string
			if json.Unmarshal([]byte(value), &params) == nil {
				f.Parameters = params
			}
		}
	}
}

// LoadEssence resolves query the way `compound product where` does (id, slug,
// name, alias, identifier, or checkout path) and returns that product's essence
// as the ledger currently holds it. When the product folds several entities
// (an app and its backend), the one carrying the essence answers.
func LoadEssence(store *mem.Store, query string) (EssenceRecord, error) {
	record, _, err := loadEssence(store, query)
	return record, err
}

// essenceContext is what a render needs beyond the record: the product's other
// current facts and its registered display name.
type essenceContext struct {
	facts map[string]mem.Claim
	name  string
}

func loadEssence(store *mem.Store, query string) (EssenceRecord, essenceContext, error) {
	query = strings.TrimSpace(query)
	where, err := Where(store, query)
	if err != nil {
		return EssenceRecord{}, essenceContext{}, err
	}
	if where.Status == WhereUnresolved || where.Status == WhereAmbiguous {
		return EssenceRecord{Query: query, Status: where.Status, Next: where.Next}, essenceContext{}, nil
	}
	view, err := store.CurrentView()
	if err != nil {
		return EssenceRecord{}, essenceContext{}, err
	}
	members := map[string]bool{}
	for _, m := range where.Members {
		members[m] = true
	}
	byEntity := map[string]map[string]mem.Claim{}
	for _, c := range view.Claims() {
		if !members[c.Entity] {
			continue
		}
		if byEntity[c.Entity] == nil {
			byEntity[c.Entity] = map[string]mem.Claim{}
		}
		if prior, seen := byEntity[c.Entity][c.Predicate]; !seen || c.Seq > prior.Seq {
			byEntity[c.Entity][c.Predicate] = c
		}
	}
	entity := essenceEntity(where.Members, where.ProductID, query, byEntity)
	record := essenceRecordFromFacts(entity, byEntity[entity])
	record.Query = query
	if record.Status == EssenceNone {
		record.Next = "no essence recorded for " + entity + "; declare product.essence in its product registry bundle and run `compound product import <product.yaml>`"
	}
	ctx := essenceContext{facts: byEntity[entity], name: strings.TrimPrefix(entity, "product:")}
	if entities, err := store.Entities(); err == nil {
		for _, e := range entities {
			if e.Slug == entity && len(e.Aliases) > 0 {
				ctx.name = e.Aliases[0]
				break
			}
		}
	}
	return record, ctx, nil
}

func essenceEntity(members []string, fallback, query string, byEntity map[string]map[string]mem.Claim) string {
	var carriers []string
	for _, m := range members {
		if hasEssenceFacts(byEntity[m]) {
			carriers = append(carriers, m)
		}
	}
	if len(carriers) == 1 {
		return carriers[0]
	}
	candidates := carriers
	if len(candidates) == 0 {
		candidates = members
	}
	for _, c := range candidates {
		if strings.EqualFold(c, query) || identityKey(c) == identityKey(query) {
			return c
		}
	}
	if len(carriers) == 0 {
		return fallback
	}
	return carriers[0]
}

// EssenceSummary is the short form served to agents: audience, problem, goal,
// stage, and constraints — the invariant a change must not break.
func EssenceSummary(e Essence) string {
	constraints := EssenceUnknown
	if len(e.Constraints) > 0 {
		constraints = strings.Join(e.Constraints, "; ")
	}
	parts := []string{
		"audience: " + clip(orUnknown(e.Audience)),
		"problem: " + clip(orUnknown(e.Problem)),
		"goal: " + goalText(e.Goal),
		"stage: " + orUnknown(e.Stage),
		"constraints: " + clip(constraints),
	}
	return strings.Join(parts, "; ")
}

func goalText(g Goal) string {
	horizon := strings.TrimSpace(g.Horizon)
	if horizon == EssenceUnknown {
		horizon = ""
	}
	switch {
	case g.IncomeTargetUSDMonth > 0 && horizon != "":
		return "USD " + strconv.FormatFloat(g.IncomeTargetUSDMonth, 'f', -1, 64) + "/month by " + horizon
	case g.IncomeTargetUSDMonth > 0:
		return "USD " + strconv.FormatFloat(g.IncomeTargetUSDMonth, 'f', -1, 64) + "/month"
	case horizon != "":
		return "income target unknown, horizon " + horizon
	}
	return EssenceUnknown
}

func orUnknown(value string) string {
	if strings.TrimSpace(value) == "" {
		return EssenceUnknown
	}
	return strings.TrimSpace(value)
}

func clip(value string) string {
	const max = 200
	if r := []rune(value); len(r) > max {
		return string(r[:max-1]) + "…"
	}
	return value
}

// EssenceUsage is the verbs' usage line, appended to productUsage().
func EssenceUsage() string {
	return "essence <product> [--json] | render-marketing <product> [--out <path>|-] [--force]"
}

// RunEssenceCLI is `compound product essence` and `compound product
// render-marketing`; args[0] names the verb.
func RunEssenceCLI(args []string, store *mem.Store, stdout, stderr io.Writer) int {
	usage := func() int {
		fmt.Fprintln(stderr, "usage: compound product "+EssenceUsage())
		return 2
	}
	if len(args) == 0 {
		return usage()
	}
	verb := args[0]
	var query, out string
	var asJSON, force, outSet bool
	for i := 1; i < len(args); i++ {
		switch arg := args[i]; {
		case arg == "--json" && verb == "essence":
			asJSON = true
		case arg == "--force" && verb == "render-marketing":
			force = true
		case arg == "--out" && verb == "render-marketing" && i+1 < len(args):
			out, outSet = args[i+1], true
			i++
		case strings.HasPrefix(arg, "-") || query != "":
			return usage()
		default:
			query = arg
		}
	}
	if query == "" || (verb != "essence" && verb != "render-marketing") {
		return usage()
	}
	record, ctx, err := loadEssence(store, query)
	if err != nil {
		fmt.Fprintf(stderr, "product %s: %v\n", verb, err)
		return 1
	}
	if verb == "essence" {
		return writeEssence(stdout, stderr, record, asJSON)
	}
	if record.Status != EssenceRecorded {
		fmt.Fprintf(stderr, "product render-marketing: %s (%s) has no essence to render; %s\n", query, record.Status, record.Next)
		return 1
	}
	body := RenderMarketing(record, ctx.name, ctx.facts)
	if out == "-" {
		fmt.Fprint(stdout, body)
		return 0
	}
	if !outSet {
		checkout := productCheckout(ctx.facts)
		if checkout == "" {
			fmt.Fprintf(stderr, "product render-marketing: no checkout recorded for %s; pass --out <path>\n", record.ProductID)
			return 1
		}
		out = filepath.Join(checkout, ".agents", "product-marketing.md")
	}
	if existing, err := os.ReadFile(out); err == nil && !force && !strings.HasPrefix(string(existing), marketingRenderMarker) {
		fmt.Fprintf(stderr, "product render-marketing: %s exists and was not rendered by compound; move its content into the product essence or pass --force\n", out)
		return 1
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fmt.Fprintln(stderr, "product render-marketing:", err)
		return 1
	}
	if err := os.WriteFile(out, []byte(body), 0o644); err != nil {
		fmt.Fprintln(stderr, "product render-marketing:", err)
		return 1
	}
	fmt.Fprintf(stdout, "# product render-marketing %s\n\n- product: %s\n- wrote: %s\n", query, record.ProductID, out)
	return 0
}

func writeEssence(stdout, stderr io.Writer, record EssenceRecord, asJSON bool) int {
	code := 0
	if record.Status == WhereUnresolved || record.Status == WhereAmbiguous {
		code = 1
	}
	if asJSON {
		blob, err := json.MarshalIndent(record, "", "  ")
		if err != nil {
			fmt.Fprintln(stderr, "product essence:", err)
			return 1
		}
		fmt.Fprintln(stdout, string(blob))
		return code
	}
	fmt.Fprintf(stdout, "# product essence %s\n\n- status: %s\n", record.Query, record.Status)
	line := func(name, value string) {
		if strings.TrimSpace(value) != "" {
			fmt.Fprintf(stdout, "- %s: %s\n", name, value)
		}
	}
	line("product", record.ProductID)
	if e := record.Essence; essenceDeclared(e) {
		line("audience", e.Audience)
		line("problem", e.Problem)
		line("value", e.Value)
		line("goal", goalText(e.Goal))
		line("stage", e.Stage)
		line("constraints", strings.Join(e.Constraints, "; "))
		line("anti_goals", strings.Join(e.AntiGoals, "; "))
	}
	line("taste standards", strings.Join(record.Taste.Standards, "; "))
	line("taste red lines", strings.Join(record.Taste.RedLines, "; "))
	for _, f := range record.Forms {
		line("form "+f.Surface+"/"+f.Stage, f.Goal+" ["+f.Status+"]")
		if len(f.Acceptance) > 0 {
			fmt.Fprintf(stdout, "  - acceptance: %s\n", strings.Join(f.Acceptance, "; "))
		}
		if len(f.Parameters) > 0 {
			fmt.Fprintf(stdout, "  - parameters: %s\n", formParameters(f.Parameters))
		}
	}
	for _, l := range record.Learned {
		label := "learned " + l.At.UTC().Format("2006-01-02")
		if l.Stage != "" {
			label += " (" + l.Stage + ")"
		}
		line(label, l.Fact+" ["+l.EvidenceRef+"]")
	}
	line("next", record.Next)
	return code
}

func formParameters(params map[string]string) string {
	keys := make([]string, 0, len(params))
	for key := range params {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	pairs := make([]string, 0, len(keys))
	for _, key := range keys {
		pairs = append(pairs, key+"="+params[key])
	}
	return strings.Join(pairs, ", ")
}

// productCheckout is the product's local checkout: the first recorded surface
// that is an existing directory on this machine.
func productCheckout(facts map[string]mem.Claim) string {
	for _, ref := range strings.Split(facts["surfaces"].Object, ",") {
		ref = strings.TrimSpace(ref)
		if !filepath.IsAbs(ref) {
			continue
		}
		if info, err := os.Stat(ref); err == nil && info.IsDir() {
			return ref
		}
	}
	return ""
}

// RenderMarketing renders .agents/product-marketing.md — the context file the
// marketing skills read first — from the product's recorded essence, under the
// section headings the product-marketing skill defines. A section the record
// cannot fill says "unknown" rather than inventing copy; local checkout paths
// are never rendered.
func RenderMarketing(record EssenceRecord, name string, facts map[string]mem.Claim) string {
	var b strings.Builder
	e := record.Essence
	fact := func(predicate string) string { return strings.TrimSpace(facts[predicate].Object) }
	section := func(heading string, lines ...string) {
		fmt.Fprintf(&b, "\n## %s\n\n", heading)
		var wrote bool
		for _, l := range lines {
			if strings.TrimSpace(l) != "" {
				fmt.Fprintf(&b, "- %s\n", l)
				wrote = true
			}
		}
		if !wrote {
			fmt.Fprintf(&b, "- %s\n", EssenceUnknown)
		}
	}
	labeled := func(label, value string) string {
		if strings.TrimSpace(value) == "" {
			return ""
		}
		return label + ": " + value
	}
	fmt.Fprintf(&b, "%s %s: edit the product essence (`compound product essence %s`), not this file -->\n", marketingRenderMarker, record.ProductID, record.ProductID)
	fmt.Fprintf(&b, "# %s — Product Marketing Context\n\n", name)
	fmt.Fprintf(&b, "> Rendered from the Compound product record `%s`. Sections the record cannot fill say `unknown`: fill them in the product declaration, re-import, and re-render.\n", record.ProductID)

	section("Product Overview",
		labeled("Product", name+" (`"+record.ProductID+"`)"),
		labeled("Positioning", fact("positioning")),
		labeled("Stage", e.Stage),
		labeled("Channels", strings.ReplaceAll(fact("channels"), ",", ", ")),
		labeled("Privacy posture", fact("privacy_posture")),
	)
	section("Target Audience", e.Audience)
	section("Personas")
	section("Problems & Pain Points", labeled("Core problem", e.Problem))
	section("Competitive Landscape")
	differentiation := []string{labeled("Value", e.Value)}
	for _, c := range e.Constraints {
		differentiation = append(differentiation, "Kept promise: "+c)
	}
	section("Differentiation", differentiation...)
	section("Objections & Anti-Personas")
	section("Switching Dynamics")
	section("Customer Language")
	section("Brand Voice",
		labeled("Taste standards", strings.Join(record.Taste.Standards, "; ")),
		labeled("Red lines", strings.Join(record.Taste.RedLines, "; ")),
	)
	var proof []string
	for _, l := range record.Learned {
		label := l.At.UTC().Format("2006-01-02")
		if l.Stage != "" {
			label += " (" + l.Stage + ")"
		}
		proof = append(proof, label+": "+l.Fact+" — evidence `"+l.EvidenceRef+"`")
	}
	section("Proof Points", proof...)
	goals := []string{labeled("Business goal", goalText(e.Goal))}
	for _, a := range e.AntiGoals {
		goals = append(goals, "Anti-goal: "+a)
	}
	for _, f := range record.Forms {
		line := f.Surface + " / " + f.Stage + ": " + orUnknown(f.Goal) + " [" + orUnknown(f.Status) + "]"
		if len(f.Acceptance) > 0 {
			line += "; acceptance: " + strings.Join(f.Acceptance, "; ")
		}
		if len(f.Parameters) > 0 {
			line += "; parameters: " + formParameters(f.Parameters)
		}
		goals = append(goals, line)
	}
	section("Goals", goals...)
	return b.String()
}
